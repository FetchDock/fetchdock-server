<?php

namespace App\Service\Integrity;

use Symfony\Component\DependencyInjection\Attribute\Autowire;

/**
 * Hashes the application files of the api image (ADR 0013).
 *
 * The image build writes the hashes to integrity-manifest.json (app:integrity:manifest); app:integrity:check hashes
 * the same files at runtime and compares. Both use the same rules, so a difference means a file changed.
 *
 * Covered: the application code, its configuration and its dependencies. Not covered: var/ (cache, logs), .env*
 * (runtime configuration), the downloader tools (installed by pip outside /app and updated at runtime) and what the
 * operator mounts on purpose: downloader configuration, JWT keys and secrets.
 */
final class IntegrityManifest
{
    public const string MANIFEST_FILE = 'integrity-manifest.json';

    /** Directories and files hashed, relative to the project directory. */
    public const array INCLUDED = ['bin', 'composer.lock', 'config', 'migrations', 'privacy', 'public', 'src', 'templates', 'vendor'];

    /** Paths below INCLUDED that are left out, with everything below them. */
    public const array EXCLUDED = [
        // Uploads (none yet) are data, not code
        'public/uploads',
        // Regenerated by Symfony on cache warmup, never loaded
        'config/reference.php',
        // Operator-provided keys and secrets
        'config/jwt',
        'config/secrets',
        // Downloader configuration, mounted by the operator (deploy/compose.yaml)
        'config/gallery-dl',
        'config/yt-dlp',
    ];

    /** File and directory names left out anywhere (bytecode caches of the Python helpers in bin/). */
    private const array EXCLUDED_NAMES = ['__pycache__', '.DS_Store'];

    public function __construct(
        #[Autowire('%kernel.project_dir%')]
        private readonly string $projectDir,
    ) {
    }

    public function path(): string
    {
        return $this->projectDir.'/'.self::MANIFEST_FILE;
    }

    /**
     * sha256 of every covered file, keyed by its path relative to the project directory, sorted by path.
     *
     * @return array<string, string>
     */
    public function hashFiles(): array
    {
        $files = [];
        foreach (self::INCLUDED as $included) {
            $path = $this->projectDir.'/'.$included;
            if (is_file($path)) {
                $files[$included] = $this->hash($path);
            } elseif (is_dir($path)) {
                $this->hashDirectory($included, $files);
            }
        }
        ksort($files, \SORT_STRING);

        return $files;
    }

    /**
     * The manifest document: {version, gitSha, files}, as JSON with a trailing newline. Its sha256 is the digest CI
     * publishes for the build.
     */
    public function build(string $appVersion, string $gitSha): string
    {
        return json_encode([
            'version' => $appVersion,
            'gitSha' => $gitSha,
            'files' => $this->hashFiles(),
        ], \JSON_PRETTY_PRINT | \JSON_UNESCAPED_SLASHES | \JSON_THROW_ON_ERROR)."\n";
    }

    /**
     * Paths that differ between the manifest's files and the current ones: changed, missing and added, sorted.
     *
     * @param array<string, string> $expected
     * @param array<string, string> $actual
     *
     * @return list<string>
     */
    public static function diff(array $expected, array $actual): array
    {
        $paths = [];
        foreach ($expected as $path => $hash) {
            if (($actual[$path] ?? null) !== $hash) {
                $paths[] = (string) $path;
            }
        }
        foreach (array_diff_key($actual, $expected) as $path => $hash) {
            $paths[] = (string) $path;
        }
        sort($paths, \SORT_STRING);

        return $paths;
    }

    /**
     * @param array<string, string> $files
     */
    private function hashDirectory(string $relative, array &$files): void
    {
        $entries = scandir($this->projectDir.'/'.$relative);
        if (false === $entries) {
            throw new \RuntimeException(\sprintf('Cannot read %s', $relative));
        }
        foreach ($entries as $name) {
            if ('.' === $name || '..' === $name || \in_array($name, self::EXCLUDED_NAMES, true)) {
                continue;
            }
            $child = $relative.'/'.$name;
            if (\in_array($child, self::EXCLUDED, true)) {
                continue;
            }
            $path = $this->projectDir.'/'.$child;
            if (is_dir($path)) {
                if (!is_link($path)) {
                    $this->hashDirectory($child, $files);
                }
            } elseif (is_file($path)) {
                $files[$child] = $this->hash($path);
            }
        }
    }

    private function hash(string $path): string
    {
        $hash = hash_file('sha256', $path);
        if (false === $hash) {
            throw new \RuntimeException(\sprintf('Cannot read %s', $path));
        }

        return $hash;
    }
}
